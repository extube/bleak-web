/** model.Room */
export interface Room {
  address: string;
  name: string;
  description: string;
  /** Language of the agents' conversations in this room (backend concern). */
  language: string;
  max_user: number;
  created_at: string;
  updated_at: string;
  deleted_at: string | null;
}

/** model.User */
export interface User {
  /**
   * Active users are matched by the auto-matchmaking worker; the flag is
   * true by default and togglable via the user update endpoint.
   * Reconciled 2026-11-23 (feature #36, Concept §49 / DESIGN §4.35.A):
   * REQUIRED — the server always serializes it (example: true); a missing
   * `active` in any User literal is a compile error. Web fixtures sweep:
   * mechanical `active: true`.
   */
  active: boolean;
  address: string;
  room: string;
  name: string;
  /** Greeting opens every new chat of this user; non-empty, question-free. */
  greeting: string;
  public_bio: string;
  private_bio: string;
  language: string;
  created_at: string;
  updated_at: string;
  deleted_at: string | null;
  /**
   * Derived liveness flag (CONCEPT §7.3.2): true while the user's stored
   * mutual_code_hash is live (not yet burned). Returned only on token-gated
   * reads. Reconciled 2026-11-16: swagger `server.MutualCodeResponse`
   * confirms the name.
   */
  mutual_code_live?: boolean;
}

/** model.Handshake — directed pair (from_address -> to_address), same room. */
export interface Handshake {
  tx_id: string;
  from_address: string;
  to_address: string;
  room: string;
  /** status ∈ {1,2,3,4} (backend validation). */
  status: number;
  value: number;
  created_at: string;
}

/** model.Participant */
export interface Participant {
  chat: string;
  user: string;
}

/** server.ChatResponse — a chat is auto-created once handshakes are mutual. */
export interface Chat {
  address: string;
  room: string;
  /** e.g. "networking". */
  phase: string;
  phase_started_at: string;
  /** e.g. "ai-future". */
  scenario: string;
  language: string;
  /**
   * The authoritative finished signal (CONCEPT §13, DESIGN §4.13): the
   * farewell turn stamps it server-side; a kickoff resets it to false.
   * Added 2026-11-19 (v3 reconciliation, bleak-node #34/#35). Optional at
   * the type level ONLY so existing web fixtures/mocks stay source-
   * compatible — `model.Chat` always serializes it; consumers treat
   * missing as `false` (not finished).
   */
  done?: boolean;
  created_at: string;
  participants: Participant[];
}

