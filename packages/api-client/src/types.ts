/**
 * Types for the bleak-node REST API — hand-translated from
 * /mount/bleak-node/docs/swagger.json (Swagger 2.0, bleak-node v0.1.0).
 *
 * The contract is small (15 endpoints) and stable; a generator was not worth
 * the tooling risk (see docs/ARCHITECTURE.md, "Data layer"). When bleak-node
 * changes its contract, update these types to match swagger.json.
 */

/** model.Room */
export interface Room {
  address: string;
  name: string;
  description: string;
  /** Language of the agents' conversations in this room (backend concern). */
  language: string;
  max_user: number;
  created_at: string;
  updated_at: string;
  deleted_at: string | null;
}

/** model.User */
export interface User {
  address: string;
  room: string;
  name: string;
  /** Greeting opens every new chat of this user; non-empty, question-free. */
  greeting: string;
  public_bio: string;
  private_bio: string;
  language: string;
  created_at: string;
  updated_at: string;
  deleted_at: string | null;
  /**
   * Derived liveness flag (CONCEPT §7.3.2): true while the user's stored
   * mutual_code_hash is live (not yet burned). Returned only on token-gated
   * reads. TBD(WP-6): confirm the field name in swagger.json.
   */
  mutual_code_live?: boolean;
}

/** model.Handshake — directed pair (from_address -> to_address), same room. */
export interface Handshake {
  tx_id: string;
  from_address: string;
  to_address: string;
  room: string;
  /** status ∈ {1,2,3,4} (backend validation). */
  status: number;
  value: number;
  created_at: string;
}

/** model.Participant */
export interface Participant {
  chat: string;
  user: string;
}

/** server.ChatResponse — a chat is auto-created once handshakes are mutual. */
export interface Chat {
  address: string;
  room: string;
  /** e.g. "networking". */
  phase: string;
  phase_started_at: string;
  /** e.g. "ai-future". */
  scenario: string;
  language: string;
  created_at: string;
  participants: Participant[];
}

/** model.Message — ≤255 symbols, tx_id/created_at generated by the server. */
export interface Message {
  tx_id: string;
  chat: string;
  from: string;
  to: string;
  content: string;
  created_at: string;
}

/** server.GreetingResponse */
export interface Greeting {
  address: string;
  greeting: string;
}

